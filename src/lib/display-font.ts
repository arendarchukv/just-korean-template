/**
 * Builds the @font-face rules for the serif display font from Fontsource's CSS, keeping only the
 * unicode-range slices that contain the given characters. The full CSS has ~95 rules (8 KB
 * brotli) in the render-blocking stylesheet; the display lines need a handful.
 */

type Rule = { id: string; css: string; ranges: [number, number][] };

function parseRules(source: string): Rule[] {
  return [
    ...source.matchAll(/\/\* gowun-batang-\[(\w+)\]-700-normal \*\/\s*(@font-face \{[^}]*\})/g),
  ].map(([, id, css]) => {
    const range = /unicode-range: ([^;]+);/.exec(css)?.[1] ?? '';
    const ranges = range.split(',').map((part) => {
      const [a, b] = part.trim().replace(/^U\+/i, '').split('-');
      return [parseInt(a, 16), parseInt(b ?? a, 16)] as [number, number];
    });
    return { id, css, ranges };
  });
}

const covers = (rule: Rule, cp: number) => rule.ranges.some(([a, b]) => cp >= a && cp <= b);

/** Slice ids whose unicode-range contains any of the non-space characters in `text`. */
export function slicesFor(source: string, text: string): string[] {
  const rules = parseRules(source);
  const codePoints = [...new Set([...text.replace(/\s/g, '')])].map((c) => c.codePointAt(0)!);
  return rules.filter((r) => codePoints.some((cp) => covers(r, cp))).map((r) => r.id);
}

/** The CSS file content: only the needed rules, with font URLs pointing into the package. */
export function displayFontCss(source: string, text: string): string {
  const needed = new Set(slicesFor(source, text));
  const rules = parseRules(source)
    .filter((r) => needed.has(r.id))
    .map((r) => r.css.replaceAll('./files/', '@fontsource/gowun-batang/files/'));
  return [
    '/* Generated by `npm run fonts` from src/lib/display-text.ts. Do not edit by hand. */',
    ...rules,
    '',
  ].join('\n');
}
